import { afterEach, describe, expect, it, vi } from 'vitest';

const mocks = vi.hoisted(() => ({
  startCampaign: vi.fn(),
  insertCampaignVariation: vi.fn(),
  setCampaignStatus: vi.fn(),
  addCreatorReference: vi.fn(),
  uploadAssetToConvex: vi.fn(),
  notifyDiscord: vi.fn(),
  scheduleVariationPosts: vi.fn(),
}));

vi.mock('@/lib/convex/http', () => ({
  startCampaign: mocks.startCampaign,
  insertCampaignVariation: mocks.insertCampaignVariation,
  setCampaignStatus: mocks.setCampaignStatus,
  addCreatorReference: mocks.addCreatorReference,
}));

vi.mock('@/lib/storage/convexAsset', () => ({
  uploadAssetToConvex: mocks.uploadAssetToConvex,
}));

vi.mock('@/lib/notify/discord', () => ({
  notifyDiscord: mocks.notifyDiscord,
}));

vi.mock('@/lib/agent/auto-mode', () => ({
  scheduleVariationPosts: mocks.scheduleVariationPosts,
}));

describe('persistGenerateAsCampaign', () => {
  afterEach(() => {
    vi.resetModules();
    for (const fn of Object.values(mocks)) fn.mockReset();
  });

  it('stages generated bytes and adds generated outputs to the creator library', async () => {
    mocks.startCampaign.mockResolvedValueOnce('campaign_1');
    mocks.uploadAssetToConvex
      .mockResolvedValueOnce({
        id: 'asset_hero',
        publicUrl: 'https://cdn.example/hero.png',
      })
      .mockResolvedValueOnce({
        id: 'asset_4x5',
        publicUrl: 'https://cdn.example/4x5.png',
      });

    const { persistGenerateAsCampaign } = await import('./persist-generation');
    await persistGenerateAsCampaign({
      workspaceId: 'demo-ws',
      baseUrl: 'https://aether.test',
      prompt: 'Generate socials for Pod cooling',
      heroImageUrl: 'data:image/png;base64,hero',
      nativePerFormatUrls: {
        '4x5': 'data:image/png;base64,format',
      },
      sourceRunId: 'run_123',
      notifyDiscord: false,
    });

    expect(mocks.uploadAssetToConvex).toHaveBeenCalledWith(
      expect.objectContaining({ workspaceId: 'demo-ws', kind: 'hero' })
    );
    expect(mocks.insertCampaignVariation).toHaveBeenCalledWith(
      expect.objectContaining({
        heroImageUrl: 'https://cdn.example/hero.png',
        nativePerFormatUrls: { '4x5': 'https://cdn.example/4x5.png' },
      })
    );
    expect(mocks.addCreatorReference).toHaveBeenCalledTimes(2);
    expect(mocks.addCreatorReference).toHaveBeenCalledWith({
      workspaceId: 'demo-ws',
      reference: expect.objectContaining({
        previewUrl: 'https://cdn.example/hero.png',
        assetId: 'asset_hero',
        origin: 'generated',
        sourceRunId: 'run_123',
        sourceCampaignId: 'campaign_1',
      }),
    });
    expect(mocks.addCreatorReference).toHaveBeenCalledWith({
      workspaceId: 'demo-ws',
      reference: expect.objectContaining({
        previewUrl: 'https://cdn.example/4x5.png',
        assetId: 'asset_4x5',
        sourceFormatId: '4x5',
      }),
    });
  });

  it('forwards explicit auto-post platform scope to publisher scheduling', async () => {
    mocks.startCampaign.mockResolvedValueOnce('campaign_1');
    mocks.insertCampaignVariation.mockResolvedValueOnce('variation_1');
    mocks.scheduleVariationPosts.mockResolvedValueOnce(['post_x']);

    const { persistGenerateAsCampaign } = await import('./persist-generation');
    await persistGenerateAsCampaign({
      workspaceId: 'demo-ws',
      baseUrl: 'https://aether.test',
      prompt: 'Generate socials for Eight Sleep Pod.',
      heroImageUrl: 'https://cdn.example/hero.png',
      nativePerFormatUrls: {
        '16x9': 'https://cdn.example/hero-16x9.png',
      },
      notifyDiscord: false,
      notifyMode: 'auto-post',
      targetPlatforms: ['x'],
    });

    expect(mocks.scheduleVariationPosts).toHaveBeenCalledWith(
      expect.objectContaining({
        workspaceId: 'demo-ws',
        forcePostNow: true,
        campaignId: 'campaign_1',
        targetPlatforms: ['x'],
      })
    );
  });
});
